import argparse
import dataclasses
import hashlib
import importlib
import json
import os
import stat
import tomllib
import warnings
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path

ENV_VAR = "WUJI_DESCRIPTION_ROOT"
PRODUCT = "hand2_2"
PRODUCT_SUBDIR = "hand2/hand2_2/body"
HANDS = ("left", "right")
MJCF_ENTRIES = {"left": "mjcf/left_with_glove.xml", "right": "mjcf/right_with_glove.xml"}
USD_ENTRIES = {"left": "usd/left_with_glove/wujihand2_2_glove.usd", "right": "usd/right_with_glove/wujihand2_2_glove.usd"}
# Product-root-relative exact paths only: a nested package.xml is part of the digest.
DIGEST_EXCLUDED = ("package.xml", "CMakeLists.txt")
PACKAGE_NAME = "wuji-hand2-2-description"
PACKAGE_MODULE = "wuji_hand2_2_description"
# Generated by the installed package; excluding them limits the digest to the files its manifest.json lists.
PACKAGE_DIGEST_EXCLUDED = ("__init__.py", "_version.py", "manifest.json")
# Compiled bytecode written next to the installed package's own .py files; never asset content.
SKIP_DIRS = frozenset({"__pycache__"})
EXPECTED_PATH = Path(__file__).resolve().parent.parent / "assets-expected.toml"

_CHUNK = 1 << 20


class AssetError(RuntimeError):
    pass


class AssetsModifiedWarning(UserWarning):
    pass


@dataclass(frozen=True)
class ResolvedAsset:
    product: str
    hand: str
    source: str
    root: Path
    mjcf: Path
    usd: Path
    digest: str
    file_count: int
    total_bytes: int
    expected_digest: str
    expected_version: str
    status: str

    @property
    def labels(self) -> list[str]:
        return ["assets modified"] if self.status == "assets-modified" else []

    def describe(self) -> str:
        return ", ".join([f"Wuji Hand 2 {self.hand}", f"hand model {self.expected_version}", *self.labels])

    def to_record(self) -> dict:
        record = dataclasses.asdict(self)
        record["root"] = str(self.root)
        record["mjcf"] = str(self.mjcf)
        record["usd"] = str(self.usd)
        record["labels"] = self.labels
        return record


def _regular_files(root: Path, excluded: tuple[str, ...] = DIGEST_EXCLUDED) -> list[tuple[str, Path]]:
    found = []
    pending = [(root, "")]
    while pending:
        directory, prefix = pending.pop()
        with os.scandir(directory) as entries:
            for entry in entries:
                rel = prefix + entry.name
                mode = entry.stat(follow_symlinks=False).st_mode
                if stat.S_ISDIR(mode):
                    if entry.name not in SKIP_DIRS:
                        pending.append((Path(entry.path), rel + "/"))
                elif stat.S_ISREG(mode):
                    if rel not in excluded:
                        found.append((rel, Path(entry.path)))
                else:
                    kind = "symbolic link" if stat.S_ISLNK(mode) else "non-regular file"
                    raise AssetError(f"product tree {root} contains a {kind}: {rel}")
    found.sort(key=lambda item: item[0])
    return found


def _file_sha256(path: Path) -> tuple[str, int]:
    h = hashlib.sha256()
    size = 0
    with open(path, "rb") as f:
        while chunk := f.read(_CHUNK):
            h.update(chunk)
            size += len(chunk)
    return h.hexdigest(), size


def _manifest(root: Path, excluded: tuple[str, ...] = DIGEST_EXCLUDED) -> tuple[str, int, int]:
    if not root.is_dir():
        raise AssetError(f"product root {root} is not a directory")
    lines = []
    total = 0
    files = _regular_files(root, excluded)
    for rel, path in files:
        digest, size = _file_sha256(path)
        lines.append(f"{digest}  {rel}\n")
        total += size
    return "".join(lines), len(files), total


def product_manifest(root: Path) -> str:
    return _manifest(Path(root))[0]


def product_digest(root: Path) -> str:
    return hashlib.sha256(product_manifest(root).encode("utf-8")).hexdigest()


def _load_expected(path: Path, *, package: bool) -> dict:
    try:
        with open(path, "rb") as f:
            table = tomllib.load(f)[PRODUCT]
        result = {"digest": table["digest"], "description_version": table["description_version"],
                  "files": table["files"], "bytes": table["bytes"]}
        if package:
            result["package_digest"] = table["package_digest"]
            result["package_files"] = table["package_files"]
            result["package_bytes"] = table["package_bytes"]
            result["package"] = table["package"]
        return result
    except (OSError, tomllib.TOMLDecodeError, KeyError) as exc:
        wanted = "digest, description_version, files and bytes"
        if package:
            wanted += ", package_digest, package_files, package_bytes and package"
        raise AssetError(f"cannot read [{PRODUCT}] {wanted} from {path}: {exc!r}") from exc


def _package_root() -> Path | None:
    try:
        module = importlib.import_module(PACKAGE_MODULE)
    except ModuleNotFoundError:
        return None
    try:
        return Path(module.root())
    except AttributeError as exc:
        raise AssetError(f"installed package {PACKAGE_NAME} has no root(): {exc!r}") from exc


def _check_package_manifest(root: Path, digest: str) -> None:
    manifest_path = root / "manifest.json"
    try:
        declared_digest = json.loads(manifest_path.read_text(encoding="utf-8"))["digest"]
    except (OSError, json.JSONDecodeError, KeyError) as exc:
        raise AssetError(f"installed package {PACKAGE_NAME} at {root} has no readable manifest.json: "
                         f"{exc!r}") from exc
    if declared_digest != digest:
        raise AssetError(
            f"installed package {PACKAGE_NAME} at {root} does not match its own manifest.json: "
            f"recomputed digest {digest}, manifest.json declares {declared_digest}"
        )


def resolve(hand: str, asset_root: Path | None = None, *, strict: bool = False,
            env: Mapping[str, str] | None = None, expected_path: Path = EXPECTED_PATH) -> ResolvedAsset:
    if hand not in HANDS:
        raise AssetError(f"hand must be one of {HANDS}, got {hand!r}")
    env = os.environ if env is None else env
    checkout_kind = f"the {PRODUCT_SUBDIR} directory of a wuji-description checkout"
    if asset_root is not None:
        source, given, origin, kind = "argument", Path(asset_root), f"--asset-root {asset_root}", checkout_kind
    elif env.get(ENV_VAR):
        source, given, origin, kind = "env", Path(env[ENV_VAR]), f"{ENV_VAR}={env[ENV_VAR]}", checkout_kind
    else:
        package_root = _package_root()
        if package_root is None:
            raise AssetError(
                f"no hand model assets for {PRODUCT}: pass --asset-root pointing at {checkout_kind}, set "
                f"{ENV_VAR} to that directory, or install the {PACKAGE_NAME} package (pixi installs it "
                "with every environment)"
            )
        source, given, origin = "package", package_root, f"installed package {PACKAGE_NAME}"
        kind = f"the hand model directory returned by {PACKAGE_MODULE}.root()"

    root = given.resolve()
    if not root.exists():
        raise AssetError(f"{origin}: {root} does not exist; expected {kind}")
    if not root.is_dir():
        raise AssetError(f"{origin}: {root} is not a directory; expected {kind}")
    mjcf = root / MJCF_ENTRIES[hand]
    usd = root / USD_ENTRIES[hand]
    if not mjcf.is_file():
        raise AssetError(f"{origin}: {mjcf} not found; expected {kind}")

    # Decided by the root's shape: an installed package passed as --asset-root still gets the package-scoped digest.
    package = (root / "manifest.json").is_file()
    expected = _load_expected(Path(expected_path), package=package)
    manifest, file_count, total_bytes = _manifest(root, PACKAGE_DIGEST_EXCLUDED if package else DIGEST_EXCLUDED)
    digest = hashlib.sha256(manifest.encode("utf-8")).hexdigest()
    if package:
        _check_package_manifest(root, digest)
        expected_digest, expected_files, expected_bytes = (
            expected["package_digest"], expected["package_files"], expected["package_bytes"])
    else:
        expected_digest, expected_files, expected_bytes = expected["digest"], expected["files"], expected["bytes"]

    status = "matches-expected"
    if digest != expected_digest:
        detail = (
            f"{PRODUCT} assets at {root} differ from {expected['description_version']}: digest {digest} "
            f"({file_count} files, {total_bytes} bytes), expected {expected_digest} "
            f"({expected_files} files, {expected_bytes} bytes) from {expected_path}"
        )
        if strict:
            raise AssetError(detail)
        warnings.warn(detail, AssetsModifiedWarning, stacklevel=2)
        status = "assets-modified"
    return ResolvedAsset(
        product=PRODUCT,
        hand=hand,
        source=source,
        root=root,
        mjcf=mjcf,
        usd=usd,
        digest=digest,
        file_count=file_count,
        total_bytes=total_bytes,
        expected_digest=expected_digest,
        expected_version=expected["description_version"],
        status=status,
    )


def add_cli_args(parser: argparse.ArgumentParser) -> None:
    parser.add_argument("--hand", required=True, choices=HANDS)
    parser.add_argument("--asset-root", type=Path, default=None,
                        help=f"{PRODUCT_SUBDIR} directory of a wuji-description checkout "
                             f"(default: ${ENV_VAR}, else the installed {PACKAGE_NAME} package)")
    parser.add_argument("--strict", action="store_true",
                        help="fail instead of warning when the asset digest differs from the expected one")
